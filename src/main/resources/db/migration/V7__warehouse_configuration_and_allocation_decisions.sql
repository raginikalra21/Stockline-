CREATE TABLE allocation_decisions (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    sku VARCHAR(24) NOT NULL,
    warehouse_code VARCHAR(16) NOT NULL,
    strategy VARCHAR(32) NOT NULL CHECK (strategy IN (
        'SINGLE_WAREHOUSE', 'NEAREST_WAREHOUSE', 'FEWEST_SPLITS',
        'MAXIMUM_AVAILABILITY', 'COST_OPTIMIZED', 'LEGACY_PRIORITY')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('RESERVED', 'FULFILLED', 'CANCELLED')),
    estimated_cost NUMERIC(12, 2),
    estimated_distance_km NUMERIC(12, 3),
    reason VARCHAR(240) NOT NULL,
    decision_metadata TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT allocation_decisions_unique UNIQUE(order_id, sku, warehouse_code),
    CONSTRAINT allocation_decisions_allocation_fk FOREIGN KEY(order_id, sku, warehouse_code)
        REFERENCES allocations(order_id, sku, warehouse_code)
);
CREATE INDEX allocation_decisions_order_idx ON allocation_decisions(order_id, sku, warehouse_code);
CREATE INDEX allocation_decisions_warehouse_idx ON allocation_decisions(warehouse_code, status, created_at DESC);

INSERT INTO allocation_decisions(order_id, sku, warehouse_code, strategy, status,
    estimated_cost, estimated_distance_km, reason, decision_metadata, created_at)
SELECT a.order_id, a.sku, a.warehouse_code, 'LEGACY_PRIORITY', o.status,
       NULL, NULL, 'Existing allocation retained during the allocation-engine migration.',
       '{"schemaVersion":1,"migrated":true}', o.created_at
FROM allocations a JOIN customer_orders o ON o.id = a.order_id
WHERE NOT EXISTS (SELECT 1 FROM allocation_decisions d WHERE d.order_id = a.order_id
                  AND d.sku = a.sku AND d.warehouse_code = a.warehouse_code);
